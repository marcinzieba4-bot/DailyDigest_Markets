def load_feed(d):
    """../feeds/<date>.json, or the committed gzip copy ../feeds/<date>.json.gz."""
    p = os.path.join(C, 'feeds', f'{d}.json')
    if os.path.exists(p):
        return json.load(open(p, encoding='utf-8'))
    import gzip
    return json.load(gzip.open(p + '.gz', 'rt', encoding='utf-8'))


def rank(x):
    s = x['src'].lower()
    tier = 0 if any(t in s for t in TIER1) else (2 if any(t in s for t in SPAM) else 1)
    return (tier, -int(x['published_at'][:10].replace('-', '')))


def line(x):
    return f"{x['id']} | {x['published_at'][:16].replace('T', ' ')} | {x['cat'][:3]} | {x['src'][:28]} | {x['title']}"


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('date'); ap.add_argument('--topic'); ap.add_argument('--grep')
    ap.add_argument('--max', type=int, default=0)
    a = ap.parse_args()
    f = load_feed(a.date)
    items = f['items']
    if a.grep:
        rx = re.compile(a.grep, re.I)
        hits = sorted([x for x in items if rx.search(x['title']) or rx.search(x['src'])], key=rank)
        for x in hits[:a.max or 400]:
            print(line(x))
        print(f'-- {len(hits)} matches'); return
    topics = [a.topic] if a.topic else sorted({t for x in items for t in x['topics']})
    cap = a.max or {'sectors': 220, 'earnings': 200, 'us_macro': 120, 'us_data': 120, 'china': 140, 'poland_pl': 120,
                    'europe': 90, 'japan': 70, 'australia': 60, 'poland_en': 60, 'crypto': 80, 'flows': 70,
                    'retail': 70, 'geo': 80, 'calendar': 30}
    for t in topics:
        sel = sorted([x for x in items if x['topics'][0] == t], key=rank)
        n = cap if isinstance(cap, int) else cap.get(t, 60)
        print(f'\n## {t} ({len(sel)} items, showing {min(n, len(sel))})')
        for x in sel[:n]:
            print(line(x))


if __name__ == '__main__':
    main()
